    Language Current()
    {
        const auto* config = Config::Instance();
        if (config == nullptr)
            return Language::English;

        return config->Language.value_or_default() == 1 ? Language::Chinese : Language::English;
    }

    bool IsChinese()
    {
        return Current() == Language::Chinese;
    }

